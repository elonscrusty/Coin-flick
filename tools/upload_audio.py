"""Upload art/sfx/*.ogg to Roblox as Audio assets (Open Cloud Assets API).

    ROBLOX_USER_ID=20194281 python3 tools/upload_audio.py [--only A,B] [--force] [--key-file PATH]

* The API key comes from --key-file (a text file holding only the key; also ROBLOX_API_KEY_FILE), ROBLOX_API_KEY, or from a Claude cloud environment "API credential" for
  apis.roblox.com (header x-api-key), which is added to requests automatically (no key needed).
* The key needs "Assets: read + write" for the creator. Audio uploads may also be held by
  Roblox moderation; a refused or failed file keeps id 0 and the error is printed and saved.
* Already uploaded files (art/sfx/uploaded_ids.json) are skipped unless --force.
* Results go to art/sfx/uploaded_ids.json and src/shared/SoundIds.luau is regenerated
  (id 0 = not uploaded; the client skips those sounds). Ids are never invented.
"""

import argparse
import json
import os
import sys
import time
import urllib.error
import urllib.request
import uuid

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SFX = os.path.join(ROOT, "art", "sfx")
IDS = os.path.join(SFX, "uploaded_ids.json")
LUAU = os.path.join(ROOT, "src", "shared", "SoundIds.luau")
API = "https://apis.roblox.com/assets/v1"
DEFAULT_USER = "20194281"


def request(method, url, key, body=None, content_type=None):
    req = urllib.request.Request(url, data=body, method=method)
    if key:  # otherwise the cloud environment's API credential adds it on the way out
        req.add_header("x-api-key", key)
    if content_type:
        req.add_header("Content-Type", content_type)
    try:
        with urllib.request.urlopen(req, timeout=120) as resp:
            return json.loads(resp.read().decode() or "{}")
    except urllib.error.HTTPError as err:
        raise RuntimeError(f"HTTP {err.code} {err.reason}: {err.read().decode(errors='replace')[:400]}") from None


def upload(path, name, key, user_id):
    boundary = uuid.uuid4().hex
    meta = {
        "assetType": "Audio",
        "displayName": f"CTR_{name}",
        "description": f"Crack the Rocks sound effect {name} (original, synthesised)",
        "creationContext": {"creator": {"userId": str(user_id)}},
    }
    with open(path, "rb") as f:
        data = f.read()
    body = b"".join([
        f"--{boundary}\r\nContent-Disposition: form-data; name=\"request\"\r\nContent-Type: application/json\r\n\r\n{json.dumps(meta)}\r\n".encode(),
        f"--{boundary}\r\nContent-Disposition: form-data; name=\"fileContent\"; filename=\"{name}.ogg\"\r\nContent-Type: audio/ogg\r\n\r\n".encode(),
        data,
        f"\r\n--{boundary}--\r\n".encode(),
    ])
    op = request("POST", f"{API}/assets", key, body, f"multipart/form-data; boundary={boundary}")
    op_path = op.get("path") or f"operations/{op.get('operationId')}"
    for _ in range(60):
        if op.get("done"):
            break
        time.sleep(2)
        op = request("GET", f"{API}/{op_path}", key)
    if not op.get("done"):
        raise RuntimeError("upload did not finish in time")
    if "error" in op:
        raise RuntimeError(json.dumps(op["error"]))
    return int(op["response"]["assetId"])


def write_luau(names, ids):
    lines = [
        "--!strict",
        "-- GENERATED by tools/upload_audio.py from art/sfx/uploaded_ids.json. Do not edit by hand.",
        "-- 0 = not uploaded: the client Audio module skips that sound. Never put guessed ids here.",
        "local SoundIds: { [string]: number } = {",
    ]
    for n in names:
        lines.append(f"\t{n} = {int(ids.get(n, 0))},")
    lines += ["}", "", "return SoundIds", ""]
    with open(LUAU, "w") as f:
        f.write("\n".join(lines))


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--only", default="")
    ap.add_argument("--force", action="store_true")
    ap.add_argument("--key-file", default=os.environ.get("ROBLOX_API_KEY_FILE", ""))
    args = ap.parse_args()
    key = os.environ.get("ROBLOX_API_KEY")
    if args.key_file:
        with open(os.path.expanduser(args.key_file)) as f:
            key = f.read().strip()  # never printed or logged
    user_id = os.environ.get("ROBLOX_USER_ID", DEFAULT_USER)
    ids = {}
    if os.path.exists(IDS):
        with open(IDS) as f:
            ids = json.load(f)
    names = sorted(fn[:-4] for fn in os.listdir(SFX) if fn.endswith(".ogg"))
    only = {x for x in args.only.split(",") if x}
    failed = {}
    for name in names:
        if only and name not in only:
            continue
        if ids.get(name) and not args.force:
            continue
        try:
            ids[name] = upload(os.path.join(SFX, f"{name}.ogg"), name, key, user_id)
            print(f"{name:<18} -> {ids[name]}")
        except Exception as err:  # keep going, report at the end
            failed[name] = str(err)
            print(f"{name:<18} FAILED: {err}")
            if "HTTP 401" in str(err) or "HTTP 403" in str(err):
                print("Permission refused: stopping early, remaining files keep id 0.")
                break
        with open(IDS, "w") as f:
            json.dump(ids, f, indent=1, sort_keys=True)
    write_luau(names, ids)
    if failed:
        sys.exit(f"{len(failed)} file(s) not uploaded; first error: {next(iter(failed.values()))}")


if __name__ == "__main__":
    main()
