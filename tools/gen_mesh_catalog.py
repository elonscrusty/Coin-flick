"""Generate src/shared/MeshIds.luau and src/shared/MeshCatalog.luau.

    python3 tools/gen_mesh_catalog.py

Inputs: art/meshes/manifest.json (blender/build.py + legacy tools/gen_meshes.py entries) and
art/meshes/uploaded_ids.json (tools/upload_meshes.py). Run after building or uploading
(upload_meshes.py runs it automatically).

MeshIds.luau     every uploaded id by name (0 = not uploaded); legacy single-mesh CT_Rocks_* names
                 and the Blender kit models.
MeshCatalog.luau the Blender kit models: sheet, pieces (slot colour, material, centre offset, size,
                 transparency, anim + pivot), attachment points, bounds. MeshService uses it to
                 rebuild each uploaded Model with the right colours, because the meshes carry none.
"""

import json
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
MANIFEST = os.path.join(ROOT, "art", "meshes", "manifest.json")
IDS = os.path.join(ROOT, "art", "meshes", "uploaded_ids.json")
OUT_IDS = os.path.join(ROOT, "src", "shared", "MeshIds.luau")
OUT_CAT = os.path.join(ROOT, "src", "shared", "MeshCatalog.luau")


def num(v):
    s = f"{v:.4f}".rstrip("0").rstrip(".")
    return "0" if s in ("-0", "") else s


def vec(v):
    return "{ " + ", ".join(num(x) for x in v) + " }"


def color(h):
    h = h.lstrip("#")
    return "Color3.fromRGB(%d, %d, %d)" % tuple(int(h[i:i + 2], 16) for i in (0, 2, 4))


def main():
    manifest = json.load(open(MANIFEST)) if os.path.exists(MANIFEST) else {}
    ids = json.load(open(IDS)) if os.path.exists(IDS) else {}
    kit = {k: v for k, v in sorted(manifest.items()) if v.get("kind") == "blender"}
    names = sorted(set(ids) | set(kit) | {k for k in manifest if k.startswith("CT_Rocks_")})

    lines = ["--!strict", "-- Generated by tools/gen_mesh_catalog.py (run by tools/upload_meshes.py). Do not edit by hand.",
             "-- 0 = not uploaded: the game keeps its procedural Part stand-in for that asset.", "return {"]
    for n in names:
        lines.append(f"\t{n} = {int(ids.get(n, 0))},")
    lines.append("}")
    open(OUT_IDS, "w").write("\n".join(lines) + "\n")

    L = [
        "--!strict",
        "-- Generated by tools/gen_mesh_catalog.py from art/meshes/manifest.json. Do not edit by hand.",
        "-- Blender kit models (blender/models/*.py, docs/MODELING.md). Roblox axes, studs, from the model",
        "-- origin (floor centre unless Origin says otherwise). Each piece is one MeshPart in the uploaded",
        "-- Model; the meshes carry no colours, so MeshService paints Color/Material/Transparency from here.",
        "-- Offset = piece centre, Size = piece size, Pivot = joint of an animated piece relative to its centre.",
        "-- Attach = named points (where kit parts, hands, rocks or lights go).",
        "",
        "export type Piece = {",
        "\tName: string,",
        "\tSlot: string,",
        "\tMaterial: string,",
        "\tColor: Color3,",
        "\tOffset: { number },",
        "\tSize: { number },",
        "\tTransparency: number?,",
        "\tAnim: string?,",
        "\tPivot: { number }?,",
        "}",
        "export type Model = {",
        "\tSheet: string,",
        "\tBounds: { { number } },",
        "\tPieces: { Piece },",
        "\tAttach: { [string]: { number } },",
        "\tOrigin: string?,",
        "}",
        "",
        "local Catalog: { [string]: Model } = {",
    ]
    for name, m in kit.items():
        L.append(f"\t{name} = {{")
        L.append(f"\t\tSheet = \"{m['sheet']}\",")
        L.append(f"\t\tBounds = {{ {vec(m['bounds'][0])}, {vec(m['bounds'][1])} }},")
        if m.get("origin"):
            L.append(f"\t\tOrigin = {json.dumps(m['origin'])},")
        att = m.get("attach", {})
        L.append("\t\tAttach = {" + ("" if not att else " " + ", ".join(f"{k} = {vec(v)}" for k, v in sorted(att.items())) + " ") + "},")
        L.append("\t\tPieces = {")
        for p in m["pieces"]:
            parts = [f"Name = \"{p['name']}\"", f"Slot = \"{p['slot']}\"", f"Material = \"{p['material']}\"",
                     f"Color = {color(m['palette'][p['slot']])}", f"Offset = {vec(p['offset'])}", f"Size = {vec(p['size'])}"]
            if p.get("transparency"):
                parts.append(f"Transparency = {num(p['transparency'])}")
            if p.get("anim"):
                parts.append(f"Anim = \"{p['anim']}\"")
            if p.get("pivot"):
                parts.append(f"Pivot = {vec(p['pivot'])}")
            L.append("\t\t\t{ " + ", ".join(parts) + " },")
        L.append("\t\t},")
        L.append("\t},")
    L += ["}", "", "return Catalog", ""]
    open(OUT_CAT, "w").write("\n".join(L))
    up = sum(1 for k in kit if ids.get(k))
    print(f"wrote MeshIds.luau ({len(names)} names) and MeshCatalog.luau ({len(kit)} kit models, {up} uploaded)")


if __name__ == "__main__":
    main()
