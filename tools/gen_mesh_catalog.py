"""Write src/shared/MeshIds.luau (ids, 0 = not uploaded) and src/shared/MeshCatalog.luau (piece colours).

    python3 tools/gen_mesh_catalog.py

Inputs: art/meshes/manifest.json (blender/build.py) and art/meshes/uploaded_ids.json (tools/upload_meshes.py).
"""

import json
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
MANIFEST = os.path.join(ROOT, "art", "meshes", "manifest.json")
IDS = os.path.join(ROOT, "art", "meshes", "uploaded_ids.json")


def color(h):
    h = h.lstrip("#")
    return "Color3.fromRGB(%d, %d, %d)" % tuple(int(h[i : i + 2], 16) for i in (0, 2, 4))


def main():
    manifest = json.load(open(MANIFEST)) if os.path.exists(MANIFEST) else {}
    ids = json.load(open(IDS)) if os.path.exists(IDS) else {}
    out = ["--!strict", "-- GENERATED by tools/gen_mesh_catalog.py. Roblox asset ids of the uploaded models; 0 = not uploaded yet.", "", "return table.freeze({"]
    for name in sorted(manifest):
        out.append(f"\t{name} = {int(ids.get(name, 0))},")
    out += ["})", ""]
    with open(os.path.join(ROOT, "src", "shared", "MeshIds.luau"), "w") as f:
        f.write("\n".join(out))
    cat = [
        "--!strict",
        "-- GENERATED by tools/gen_mesh_catalog.py. The FBX files carry no colours: MeshService paints each piece from here.",
        "",
        "export type Piece = { color: Color3, material: string } -- material = Enum.Material name",
        "",
        "local Catalog: { [string]: { [string]: Piece } } = {",
    ]
    for name in sorted(manifest):
        cat.append(f"\t{name} = {{")
        for slot, info in manifest[name]["pieces"].items():
            cat.append(f'\t\t{slot} = {{ color = {color(info["color"])}, material = "{info["material"]}" }},')
        cat.append("\t},")
    cat += ["}", "", "return Catalog", ""]
    with open(os.path.join(ROOT, "src", "shared", "MeshCatalog.luau"), "w") as f:
        f.write("\n".join(cat))
    print(f"{len(manifest)} models, {sum(1 for n in manifest if ids.get(n))} uploaded")


main()
